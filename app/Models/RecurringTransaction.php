<?php

namespace App\Models;

use Carbon\CarbonImmutable;
use Database\Factories\RecurringTransactionFactory;
use DateTimeInterface;
use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;

#[Fillable(['category_id', 'description', 'amount', 'type', 'frequency', 'start_date', 'end_date', 'next_occurrence_date'])]
class RecurringTransaction extends Model
{
    /** @use HasFactory<RecurringTransactionFactory> */
    use HasFactory;

    /**
     * Get the attributes that should be cast.
     *
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'amount' => 'decimal:2',
            'start_date' => 'date',
            'end_date' => 'date',
            'next_occurrence_date' => 'date',
        ];
    }

    /**
     * Get the user who owns the recurring transaction.
     *
     * @return BelongsTo<User, $this>
     */
    public function user(): BelongsTo
    {
        return $this->belongsTo(User::class);
    }

    /**
     * Get the category assigned to the recurring transaction.
     *
     * @return BelongsTo<Category, $this>
     */
    public function category(): BelongsTo
    {
        return $this->belongsTo(Category::class);
    }

    /**
     * Get the transactions generated by this recurring transaction.
     *
     * @return HasMany<Transaction, $this>
     */
    public function transactions(): HasMany
    {
        return $this->hasMany(Transaction::class);
    }

    public function nextOccurrenceAfter(DateTimeInterface $date): CarbonImmutable
    {
        $date = CarbonImmutable::instance($date);

        return match ($this->frequency) {
            'daily' => $date->addDay(),
            'weekly' => $date->addWeek(),
            'monthly' => $this->nextMonthlyOccurrence($date),
            'yearly' => $this->nextYearlyOccurrence($date),
        };
    }

    private function nextMonthlyOccurrence(CarbonImmutable $date): CarbonImmutable
    {
        $nextMonth = $date->startOfMonth()->addMonth();

        return $nextMonth->setDay(min($this->start_date->day, $nextMonth->daysInMonth));
    }

    private function nextYearlyOccurrence(CarbonImmutable $date): CarbonImmutable
    {
        $nextYear = $date->startOfYear()->addYear();
        $day = min($this->start_date->day, $nextYear->daysInMonth);

        return $nextYear->setDate($nextYear->year, $this->start_date->month, $day);
    }
}
